public class PI {
    public static void main(String[] args) {

        int number = 8;
        System.out.println(number % 2);
        
        int result = 5 + 3 * 2;
        
        System.out.println(result);
        System.out.println(10 / 3);
        System.out.println(10.0 / 3);
        System.out.println(10 % 3);
    }
}